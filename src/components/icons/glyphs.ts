/** Small filled circle as a path. */
const dot = (x: number, y: number, r = 1.05) =>
  `M${x - r} ${y}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0z`;

/** Four-point sparkle centred at (x, y). */
const sparkle = (x: number, y: number, r: number) => {
  const k = r * 0.28;
  return `M${x} ${y - r}Q${x + k} ${y - k} ${x + r} ${y}Q${x + k} ${y + k} ${x} ${y + r}Q${x - k} ${y + k} ${x - r} ${y}Q${x - k} ${y - k} ${x} ${y - r}z`;
};

/** Sun rays around (cx, cy): n rays from radius r1 to r2, optionally only the upper half. */
const rays = (cx: number, cy: number, r1: number, r2: number, angles: number[]) =>
  angles
    .map((deg) => {
      const a = (deg * Math.PI) / 180;
      const f = (n: number) => Math.round(n * 100) / 100;
      return `M${f(cx + r1 * Math.cos(a))} ${f(cy - r1 * Math.sin(a))}L${f(cx + r2 * Math.cos(a))} ${f(cy - r2 * Math.sin(a))}`;
    })
    .join('');

